/// The circulant diffusion row of the Whirlpool mixing layer.
const CIRC: [u8; 8] = [1, 1, 4, 1, 8, 5, 2, 9];

/// Multiply in GF(2^8) modulo x^8 + x^4 + x^3 + x^2 + 1 (0x11d).
const fn gf_mul(mut a: u8, mut b: u8) -> u8 {
    let mut r = 0u8;
    while b != 0 {
        if b & 1 != 0 {
            r ^= a;
        }
        let hi = a & 0x80;
        a <<= 1;
        if hi != 0 {
            a ^= 0x1d;
        }
        b >>= 1;
    }
    r
}

/// The combined lookup table: 256 product rows (one per S-box entry) plus
/// the 10 round constants, in the OpenSSL `Cx` byte layout.
pub(crate) static TABLE: [u64; 266] = {
    let mut t = [0u64; 266];
    let mut x = 0;
    while x < 256 {
        let mut row = [0u8; 8];
        let mut k = 0;
        while k < 8 {
            row[k] = gf_mul(SBOX[x], CIRC[k]);
            k += 1;
        }
        t[x] = u64::from_le_bytes(row);
        x += 1;
    }
    // Round constant r is the S-box row r*8..r*8+8.
    let mut r = 0;
    while r < 10 {
        let mut row = [0u8; 8];
        let mut k = 0;
        while k < 8 {
            row[k] = SBOX[8 * r + k];
            k += 1;
        }
        t[256 + r] = u64::from_le_bytes(row);
        r += 1;
    }
    t
};

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sbox_canonical_head_and_tail() {
        // Canonical Whirlpool S-box entries (ISO/IEC 10118-3).
        assert_eq!(SBOX[0], 0x18);
        assert_eq!(SBOX[1], 0x23);
        assert_eq!(SBOX[0xff], 0x86);
    }

    #[test]
    fn round_constants_canonical() {
        // RC[r] is stored as the raw S-box bytes (spec big-endian lane
        // order); the internal u64s read them little-endian, matching the
        // OpenSSL Cx union layout.
        assert_eq!(
            TABLE[256].to_le_bytes(),
            [0x18, 0x23, 0xc6, 0xe8, 0x87, 0xb8, 0x01, 0x4f]
        );
        assert_eq!(
            TABLE[264].to_le_bytes(),
            [0xfb, 0xee, 0x7c, 0x66, 0xdd, 0x17, 0x47, 0x9e]
        );
        assert_eq!(
            TABLE[265].to_le_bytes(),
            [0xca, 0x2d, 0xbf, 0x07, 0xad, 0x5a, 0x83, 0x33]
        );
    }

    #[test]
    fn table_rows_are_circulant_products() {
        for x in 0..256usize {
            let row = TABLE[x].to_le_bytes();
            for (k, c) in CIRC.iter().enumerate() {
                assert_eq!(row[k], gf_mul(SBOX[x], *c), "x={x} k={k}");
            }
        }
    }
}
