use super::*;
use crate::block::aes::Aes;

// Reference values produced by OpenSSL 3.5.8 `openssl mac GMAC`
// (GMAC == GCM with empty plaintext, message as AAD). The empty-message
// case coincides with McGrew/Viega GCM test case 1.
const ZERO_KEY: [u8; 16] = [0u8; 16];
const ZERO_IV: [u8; 12] = [0u8; 12];

#[test]
fn empty_message() {
    let tag = sum(Aes::new(&ZERO_KEY).unwrap(), &ZERO_IV, b"").unwrap();
    assert_eq!(
        tag,
        [
            0x58, 0xe2, 0xfc, 0xce, 0xfa, 0x7e, 0x30, 0x61, 0x36, 0x7f, 0x1d, 0x57, 0xa4, 0xe7,
            0x45, 0x5a,
        ]
    );
}

#[test]
fn mcgrew_gcm_aad_message() {
    // Message: feedfacedeadbeeffeedfacedeadbeefabaddad2 (20 bytes),
    // key feffe9928665731c6d6a8f9467308308, IV cafebabefacedbaddecaf888.
    let key = [
        0xfe, 0xff, 0xe9, 0x92, 0x86, 0x65, 0x73, 0x1c, 0x6d, 0x6a, 0x8f, 0x94, 0x67, 0x30, 0x83,
        0x08,
    ];
    let iv = [
        0xca, 0xfe, 0xba, 0xbe, 0xfa, 0xce, 0xdb, 0xad, 0xde, 0xca, 0xf8, 0x88,
    ];
    let msg = [
        0xfe, 0xed, 0xfa, 0xce, 0xde, 0xad, 0xbe, 0xef, 0xfe, 0xed, 0xfa, 0xce, 0xde, 0xad, 0xbe,
        0xef, 0xab, 0xad, 0xda, 0xd2,
    ];

    let tag = sum(Aes::new(&key).unwrap(), &iv, &msg).unwrap();
    assert_eq!(
        tag,
        [
            0x34, 0x64, 0x34, 0xfd, 0x51, 0xd5, 0xcd, 0x0c, 0x58, 0x87, 0xec, 0x63, 0xe3, 0x9b,
            0x90, 0x7a,
        ]
    );
}

#[test]
fn short_and_long_messages() {
    let key = [
        0xfe, 0xff, 0xe9, 0x92, 0x86, 0x65, 0x73, 0x1c, 0x6d, 0x6a, 0x8f, 0x94, 0x67, 0x30, 0x83,
        0x08,
    ];
    let iv = [
        0xca, 0xfe, 0xba, 0xbe, 0xfa, 0xce, 0xdb, 0xad, 0xde, 0xca, 0xf8, 0x88,
    ];

    let tag = sum(Aes::new(&key).unwrap(), &iv, b"abc").unwrap();
    assert_eq!(
        tag,
        [
            0x0a, 0x08, 0x64, 0xa9, 0x5b, 0x78, 0xbc, 0x12, 0xdf, 0x9a, 0x77, 0xe6, 0x7c, 0x11,
            0x55, 0x75,
        ]
    );
}

#[test]
fn multi_block_streaming() {
    // 40-byte message (SP 800-38A block sequence), zero key/IV.
    let msg: [u8; 40] = [
        0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96, 0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17,
        0x2a, 0xae, 0x2d, 0x8a, 0x57, 0x1e, 0x03, 0xac, 0x9c, 0x9e, 0xb7, 0x6f, 0xac, 0x45, 0xaf,
        0x8e, 0x51, 0x30, 0xc8, 0x1c, 0x46, 0xa3, 0x5c, 0xe4, 0x11,
    ];
    let expected = sum(Aes::new(&ZERO_KEY).unwrap(), &ZERO_IV, &msg).unwrap();
    assert_eq!(
        expected,
        [
            0xa8, 0x71, 0x83, 0x82, 0xcf, 0x67, 0x98, 0xa2, 0x5b, 0xd0, 0x11, 0xff, 0xf9, 0x8e,
            0xe9, 0xbf,
        ]
    );

    // Streaming in odd-sized chunks must match the one-shot result.
    let mut mac = Gmac::new(Aes::new(&ZERO_KEY).unwrap(), &ZERO_IV).unwrap();
    for chunk in msg.chunks(9) {
        mac.write(chunk);
    }
    assert!(mac.verify(&expected));
}

#[test]
fn wrong_tag_fails() {
    let mut mac = Gmac::new(Aes::new(&ZERO_KEY).unwrap(), &ZERO_IV).unwrap();
    mac.write(b"abc");
    let mut bad = sum(Aes::new(&ZERO_KEY).unwrap(), &ZERO_IV, b"abc").unwrap();
    bad[0] ^= 1;
    assert!(!mac.verify(&bad));
}
