#[test]
fn rfc4493_aes128() {
    let cases: &[(&[u8], [u8; 16])] = &[
        (
            b"",
            [
                0xbb, 0x1d, 0x69, 0x29, 0xe9, 0x59, 0x37, 0x28, 0x7f, 0xa3, 0x7d, 0x12, 0x9b, 0x75,
                0x67, 0x46,
            ],
        ),
        (
            &M16,
            [
                0x07, 0x0a, 0x16, 0xb4, 0x6b, 0x4d, 0x41, 0x44, 0xf7, 0x9b, 0xdd, 0x9d, 0xd0, 0x4a,
                0x28, 0x7c,
            ],
        ),
        (
            &M40,
            [
                0xdf, 0xa6, 0x67, 0x47, 0xde, 0x9a, 0xe6, 0x30, 0x30, 0xca, 0x32, 0x61, 0x14, 0x97,
                0xc8, 0x27,
            ],
        ),
        (
            &M64,
            [
                0x51, 0xf0, 0xbe, 0xbf, 0x7e, 0x3b, 0x9d, 0x92, 0xfc, 0x49, 0x74, 0x17, 0x79, 0x36,
                0x3c, 0xfe,
            ],
        ),
    ];

    for (msg, expected) in cases {
        let tag = sum(Aes::new(&RFC4493_KEY).unwrap(), msg).unwrap();
        assert_eq!(&tag, expected, "CMAC-AES128 len={}", msg.len());

        let mut mac = Cmac::<Aes, 16>::new(Aes::new(&RFC4493_KEY).unwrap()).unwrap();
        // Feed in odd-sized chunks to exercise the buffering paths.
        for chunk in msg.chunks(7) {
            mac.write(chunk);
        }
        assert!(mac.verify(expected), "streaming CMAC len={}", msg.len());
    }
}

#[test]
fn triple_des_cmac() {
    // OpenSSL test/recipes/30-test_evp_data/evpmac_cmac_des.txt
    // (MAC = CMAC, Algorithm = DES-EDE3-CBC).
    let key = [
        0x89, 0xbc, 0xd9, 0x52, 0xa8, 0xc8, 0xab, 0x37, 0x1a, 0xf4, 0x8a, 0xc7, 0xd0, 0x70, 0x85,
        0xd5, 0xef, 0xf7, 0x02, 0xe6, 0xd6, 0x2c, 0xdc, 0x23,
    ];
    let msg: [u8; 32] = [
        0xfa, 0x62, 0x0c, 0x1b, 0xbe, 0x97, 0x31, 0x9e, 0x9a, 0x0c, 0xf0, 0x49, 0x21, 0x21, 0xf7,
        0xa2, 0x0e, 0xb0, 0x8a, 0x6a, 0x70, 0x9d, 0xcb, 0xd0, 0x0a, 0xaf, 0x38, 0xe4, 0xf9, 0x9e,
        0x75, 0x4e,
    ];
    let expected: [u8; 8] = [0x8f, 0x49, 0xa1, 0xb7, 0xd6, 0xaa, 0x22, 0x58];

    let tag = sum(TripleDes::new(&key).unwrap(), &msg).unwrap();
    assert_eq!(tag, expected);
}

#[test]
fn block_size_mismatch_rejected() {
    // TripleDes has an 8-byte block; a 16-byte CMAC must refuse it.
    assert!(Cmac::<TripleDes, 16>::new(TripleDes::new(&[0u8; 24]).unwrap()).is_err());
}

#[test]
fn write_after_sum_panics() {
    let mut mac = Cmac::<Aes, 16>::new(Aes::new(&RFC4493_KEY).unwrap()).unwrap();
    let _ = mac.sum();
    let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        mac.write(b"more");
    }));
    assert!(result.is_err());
}
